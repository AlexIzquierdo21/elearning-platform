package com.elearning.elearning_platform.course.domain.port.out;

import com.elearning.elearning_platform.course.domain.model.Course;
import com.elearning.elearning_platform.course.domain.model.CourseStatus;
import com.elearning.elearning_platform.course.domain.valueobject.CategoryId;
import com.elearning.elearning_platform.course.domain.valueobject.CourseId;
import com.elearning.elearning_platform.user.domain.valueobject.UserId;

import java.util.List;
import java.util.Optional;

/**
 * Represents a contract for managing and retrieving {@code Course} entities from a data source.
 *
 * This interface defines the operations necessary for interacting with the underlying
 * persistence mechanism to create, read, update, and delete course records.
 * It also provides methods for querying courses based on various criteria, such as
 * their unique identifier, instructor, category, or status.
 *
 * Implementations of this interface are responsible for the actual integration
 * with the storage system (e.g., database, in-memory storage, etc.).
 */
public interface CourseRepositoryPort {

    /**
     * Persists a {@code Course} entity to the underlying data source.
     *
     * If the course does not already exist, it will be created. If the course already exists,
     * the existing record will be updated with the provided course's details.
     *
     * @param course the {@code Course} entity to be saved, must not be null
     * @return the saved {@code Course} entity, which includes any updates
     *         made (such as autogenerated fields like ID or timestamps)
     */
    Course save(Course course);

    /**
     * Retrieves a {@code Course} entity by its unique identifier.
     *
     * This method searches the underlying data source for a course that matches
     * the given {@code CourseId}. If a match is found, the course is returned
     * wrapped in an {@code Optional}. If no such course exists, an empty {@code Optional}
     * is returned.
     *
     * @param id the unique identifier of the {@code Course} to retrieve, must not be null
     * @return an {@code Optional} containing the matching {@code Course} if found, or empty if not found
     */
    Optional<Course> findById(CourseId id);

    /**
     * Retrieves a list of {@code Course} entities associated with the given instructor.
     *
     * This method searches the underlying data source for courses that are linked to
     * the specified {@code UserId} of an instructor. It returns all matching courses
     * or an empty list if no courses are found for the provided instructor ID.
     *
     * @param instructorId the unique identifier of the instructor whose courses are to be retrieved, must not be null
     * @return a list of {@code Course} entities taught by the instructor, or an empty list if no matching courses are found
     */
    List<Course> findByInstructorId(UserId instructorId);

    /**
     * Retrieves a list of {@code Course} entities with the specified status.
     *
     * This method searches the underlying data source for courses that match the
     * given {@code CourseStatus}. It returns all matching courses or an empty list
     * if no courses are found with the specified status.
     *
     * @param status the {@code CourseStatus} of the courses to retrieve, must not be null
     * @return a list of {@code Course} entities with the specified status, or an empty list if no matching courses are found
     */
    List<Course> findByStatus(CourseStatus status);

    /**
     * Retrieves a list of {@code Course} entities associated with the specified category ID.
     *
     * This method searches the underlying data source for courses that belong to the given
     * {@code CategoryId}. It returns all matching courses or an empty list if no courses
     * are found for the specified category.
     *
     * @param categoryId the unique identifier of the category whose courses are to be retrieved; must not be null
     * @return a list of {@code Course} entities belonging to the specified category, or an empty list if no matching courses are found
     */
    List<Course> findByCategoryId(CategoryId categoryId);

    /**
     * Deletes a {@code Course} entity identified by its unique identifier.
     *
     * This method removes the course record associated with the provided {@code CourseId}
     * from the underlying data source. If no course exists with the given identifier,
     * no action is performed.
     *
     * @param id the unique identifier of the {@code Course} to be deleted; must not be null
     */
    void deleteById(CourseId id);

    /**
     * Checks if a {@code Course} entity exists in the underlying data source
     * for the provided unique identifier.
     *
     * @param id the unique identifier of the {@code Course} to check for existence; must not be null
     * @return {@code true} if a {@code Course} with the given identifier exists, {@code false} otherwise
     */
    boolean existsById(CourseId id);

    /**
     * Retrieves all {@code Course} entities from the underlying data source.
     *
     * This method returns a list containing all available courses. If no courses exist,
     * the returned list will be empty.
     *
     * @return a list of all {@code Course} entities, or an empty list if no courses are found
     */
    List<Course> findAll();
}
