package com.elearning.elearning_platform.course.domain.port.out;

import com.elearning.elearning_platform.course.domain.model.Category;
import com.elearning.elearning_platform.course.domain.valueobject.CategoryId;

import java.util.List;
import java.util.Optional;

/**
 * Defines an abstraction for interacting with the persistence layer
 * related to Category entities. Implementations of this interface
 * should provide the necessary mechanisms for storing, retrieving,
 * and managing Category instances.
 *
 * This serves as a port in a hexagonal architecture, decoupling
 * the domain layer from the details of persistence.
 */
public interface CategoryRepositoryPort {

    /**
     * Persists the given Category instance to the data store. This method is
     * responsible for saving a new Category or updating an existing one
     * based on its unique identifier.
     *
     * @param category the Category instance to be saved; must not be null
     * @return the persisted Category instance, potentially updated with additional
     *         metadata (e.g., timestamps or autogenerated fields) from the data store
     */
    Category save(Category category);

    /**
     * Retrieves a Category instance by its unique identifier.
     *
     * This method attempts to find a Category in the persistence layer
     * that matches the provided {@link CategoryId}. If no Category is found
     * with the given identifier, an empty {@link Optional} is returned.
     *
     * @param id the unique identifier of the Category to be retrieved; must not be null
     * @return an {@link Optional} containing the retrieved Category if found, or an empty {@link Optional} if not
     */
    Optional<Category> findById(CategoryId id);

    /**
     * Retrieves all Category instances from the persistence layer.
     *
     * This method fetches all available categories irrespective of their
     * attributes, such as active status or any other filter criteria.
     *
     * @return a list of all Category instances; if no categories exist, returns an empty list
     */
    List<Category> findAll();

    /**
     * Retrieves a list of Category instances filtered by their active status.
     *
     * This method fetches all categories that have their "active" status
     * matching the provided boolean parameter. If no categories match the
     * specified status, the method returns an empty list.
     *
     * @param active a boolean indicating the desired active status;
     *               true to retrieve active categories,
     *               false to retrieve inactive categories
     * @return a list of Category instances matching the specified active status;
     *         if no matching categories exist, returns an empty list
     */
    List<Category> findByActive(boolean active);

    /**
     * Finds a Category entity by its unique slug.
     *
     * This method retrieves a {@link Category} from the persistence layer
     * that has a slug matching the provided value. If no such Category exists,
     * an empty {@link Optional} is returned.
     *
     * @param slug the unique slug of the Category to be retrieved; must not be null or empty
     * @return an {@link Optional} containing the matching Category if found,
     * or an empty {@link Optional} if no match exists
     */
    Optional<Category> findBySlug(String slug);

    /**
     * Checks whether a Category entity exists in the data store for the given unique identifier.
     *
     * @param id the unique identifier of the Category to check for existence; must not be null
     * @return true if a Category entity with the specified identifier exists, false otherwise
     */
    boolean existsById(CategoryId id);
}
